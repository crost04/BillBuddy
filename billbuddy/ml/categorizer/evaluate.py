"""Evaluation of the categorizer on the sample data (CRISP-DM: data understanding,
modeling and evaluation). Writes docs/categorizer-report.md.

Usage: python -m billbuddy.ml.categorizer.evaluate
"""

import datetime as dt

import numpy as np
import pandas as pd
from sklearn.dummy import DummyClassifier
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, f1_score
from sklearn.model_selection import GroupKFold, StratifiedKFold, cross_val_predict, cross_validate
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline

from billbuddy.db import PROJECT_ROOT
from billbuddy.ml.categorizer.model import MIN_CONFIDENCE, build_pipeline, to_frame
from billbuddy.ml.categorizer.training_data import SAMPLE_CSV

REPORT_PATH = PROJECT_ROOT / "docs" / "categorizer-report.md"
SEED = 42
FOLDS = 5


def load() -> pd.DataFrame:
    df = pd.read_csv(SAMPLE_CSV)
    # Duplicates would put identical rows into training and test data
    df = df[~df.is_duplicate].reset_index(drop=True)
    df["amount"] = df.amount_cents / 100
    return df


def text_only(vectorizer, classifier) -> Pipeline:
    # Wrapper so text-only models accept the same DataFrame as the final model
    from sklearn.compose import ColumnTransformer

    return Pipeline([("features", ColumnTransformer([("text", vectorizer, "text")])), ("classifier", classifier)])


def candidates() -> dict:
    return {
        "Baseline: always the most frequent category": DummyClassifier(strategy="most_frequent"),
        "Word TF-IDF + logistic regression": text_only(
            TfidfVectorizer(analyzer="word"), LogisticRegression(C=10, class_weight="balanced", max_iter=2000)
        ),
        "Character TF-IDF + naive Bayes": text_only(
            TfidfVectorizer(analyzer="char_wb", ngram_range=(2, 5), sublinear_tf=True), MultinomialNB(alpha=0.1)
        ),
        "Character TF-IDF + logistic regression (chosen)": build_pipeline(use_amount=False),
        "Character TF-IDF + amount + logistic regression": build_pipeline(use_amount=True),
    }


def table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def percent(value: float) -> str:
    return f"{value * 100:.1f} %"


def main() -> None:
    df = load()
    X = to_frame(df.description, df.amount)
    y = df.category
    stratified = StratifiedKFold(FOLDS, shuffle=True, random_state=SEED)
    report = [
        "# Categorizer – evaluation report",
        "",
        f"Generated by `python -m billbuddy.ml.categorizer.evaluate` on {dt.date.today()} "
        f"(sample data, random seed {SEED}, {FOLDS}-fold cross-validation).",
    ]

    # --- Data understanding ---
    counts = y.value_counts()
    words = df.description.str.split().str.len()
    with_digits = df.description.str.contains(r"\d").mean()
    capitals_only = (df.description == df.description.str.upper()).mean()
    report += [
        "",
        "## 1. Data understanding",
        "",
        f"- {len(df)} expenses (without duplicates), {df.merchant.nunique()} different shops, "
        f"{y.nunique()} categories",
        f"- Description length: median {words.median():.0f} word(s), max {words.max()}",
        f"- {percent(with_digits)} of the descriptions contain digits (amounts like \"34,50\"), "
        f"{percent(capitals_only)} are written in capitals only → cleaning needed",
        f"- Imbalanced classes: the largest category has {counts.max()} rows, the smallest {counts.min()}",
        "",
        table(
            ["Category", "Rows", "Share", "Median amount", "Min", "Max"],
            [
                [cat, n, percent(n / len(df)), f"{df.amount[y == cat].median():.2f} €",
                 f"{df.amount[y == cat].min():.2f} €", f"{df.amount[y == cat].max():.2f} €"]
                for cat, n in counts.items()
            ],
        ),
    ]

    # --- Model comparison ---
    rows = []
    for name, model in candidates().items():
        scores = cross_validate(model, X, y, cv=stratified, scoring=["accuracy", "f1_macro"])
        rows.append([
            name,
            f"{percent(scores['test_accuracy'].mean())} ± {percent(scores['test_accuracy'].std())}",
            f"{percent(scores['test_f1_macro'].mean())} ± {percent(scores['test_f1_macro'].std())}",
        ])
    report += [
        "",
        "## 2. Model comparison",
        "",
        "Accuracy = share of correct categories. Macro F1 = average F1 score over all categories, so rare "
        "categories count as much as frequent ones (important here because of the imbalance).",
        "",
        table(["Model", "Accuracy", "Macro F1"], rows),
    ]

    chosen = build_pipeline()

    # --- Unseen shops ---
    by_shop = GroupKFold(FOLDS)
    unseen = cross_validate(chosen, X, y, cv=by_shop, groups=df.merchant, scoring=["accuracy", "f1_macro"])
    unseen_amount = cross_validate(
        build_pipeline(use_amount=True), X, y, cv=by_shop, groups=df.merchant, scoring=["accuracy", "f1_macro"]
    )
    report += [
        "",
        "## 3. Shops the model has never seen",
        "",
        "In the comparison above, the same shop can appear in training and test data – realistic, because "
        "people shop at the same places again and again. To see how well the model generalizes, here the "
        "test data only contains shops that are missing from the training data (grouped cross-validation by shop):",
        "",
        table(
            ["Model", "Accuracy", "Macro F1"],
            [
                ["Text only (chosen)", percent(unseen["test_accuracy"].mean()), percent(unseen["test_f1_macro"].mean())],
                ["Text + amount", percent(unseen_amount["test_accuracy"].mean()),
                 percent(unseen_amount["test_f1_macro"].mean())],
            ],
        ),
        "",
        "Unknown shops are much harder: the model can only use similar spellings (\"Kletterwald\" ~ "
        "\"Kletterhalle\"). The amount does not help here either. This is why learning from the user's own "
        "categories matters, and why the app makes no suggestion when it is unsure.",
    ]

    # --- Errors per category ---
    probabilities = cross_val_predict(chosen, X, y, cv=stratified, method="predict_proba")
    classes = np.array(sorted(y.unique()))
    predicted = classes[probabilities.argmax(axis=1)]
    per_class = classification_report(y, predicted, output_dict=True, zero_division=0)
    confusions = (
        pd.DataFrame({"true": y, "predicted": predicted})
        .query("true != predicted")
        .value_counts()
        .head(8)
    )
    report += [
        "",
        "## 4. Results per category (chosen model)",
        "",
        table(
            ["Category", "Precision", "Recall", "F1", "Rows"],
            [
                [cat, percent(per_class[cat]["precision"]), percent(per_class[cat]["recall"]),
                 percent(per_class[cat]["f1-score"]), int(per_class[cat]["support"])]
                for cat in counts.index
            ],
        ),
        "",
        "Precision: how many suggestions of this category were right. Recall: how many expenses of this "
        "category were found.",
        "",
        "Most frequent mistakes:",
        "",
        table(["True category", "Predicted", "Count"], [[t, p, n] for (t, p), n in confusions.items()]),
    ]

    # --- Confidence threshold ---
    confidence = probabilities.max(axis=1)
    unseen_probabilities = cross_val_predict(chosen, X, y, cv=by_shop, groups=df.merchant, method="predict_proba")
    unseen_predicted = classes[unseen_probabilities.argmax(axis=1)]
    unseen_confidence = unseen_probabilities.max(axis=1)

    def coverage_and_accuracy(conf, pred, threshold):
        shown = conf >= threshold
        accuracy = percent(accuracy_score(y[shown], pred[shown])) if shown.any() else "–"
        return [percent(shown.mean()), accuracy]

    rows = []
    for threshold in (0.0, 0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9):
        rows.append(
            [f"{threshold:.1f}" + (" (used)" if threshold == MIN_CONFIDENCE else "")]
            + coverage_and_accuracy(confidence, predicted, threshold)
            + coverage_and_accuracy(unseen_confidence, unseen_predicted, threshold)
        )
    report += [
        "",
        "## 5. Confidence threshold",
        "",
        "The app only makes a suggestion if the model's probability reaches a threshold. A higher threshold "
        "means fewer but more reliable suggestions. Known shops: as in section 2; unseen shops: as in section 3.",
        "",
        table(
            ["Threshold", "Known shops: with suggestion", "Known shops: correct",
             "Unseen shops: with suggestion", "Unseen shops: correct"],
            rows,
        ),
        "",
        f"Chosen: {MIN_CONFIDENCE}. For known shops it costs almost nothing, for unseen shops it clearly reduces "
        "wrong suggestions – and a wrong suggestion is worse than none, because the user has to notice and fix it.",
    ]

    # --- Learning curve (cold start) ---
    rows = []
    rng = np.random.default_rng(SEED)
    for size in (25, 50, 100, 200, 400):
        f1s = []
        for train_idx, test_idx in stratified.split(X, y):
            subset = rng.choice(train_idx, size=min(size, len(train_idx)), replace=False)
            if y.iloc[subset].nunique() < 2:
                continue
            model = build_pipeline().fit(X.iloc[subset], y.iloc[subset])
            f1s.append(f1_score(y.iloc[test_idx], model.predict(X.iloc[test_idx]), average="macro"))
        rows.append([size, percent(np.mean(f1s))])
    report += [
        "",
        "## 6. How much data is needed? (learning curve)",
        "",
        "Macro F1 when the model is trained on only a part of the data:",
        "",
        table(["Training examples", "Macro F1"], rows),
        "",
    ]

    REPORT_PATH.write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    print(f"\nWritten to {REPORT_PATH}")


if __name__ == "__main__":
    main()
