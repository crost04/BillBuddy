"""Backtesting of the month-end forecast on the sample data (CRISP-DM: data
understanding, modeling and evaluation). Writes docs/forecast-report.md.

Backtesting: pretend it is day 5, 10, 15, 20 or 25 of a past month, forecast
with only the data known on that day, and compare with what really happened.

Usage: python -m billbuddy.ml.forecast.evaluate
"""

import csv
import datetime as dt
from statistics import mean, median, pstdev

from sklearn.linear_model import LinearRegression

from billbuddy.db import PROJECT_ROOT
from billbuddy.ml.categorizer.training_data import SAMPLE_CSV
from billbuddy.ml.forecast.model import Record, forecast_month, history_months, spent_until

REPORT_PATH = PROJECT_ROOT / "docs" / "forecast-report.md"
CHECK_DAYS = (5, 10, 15, 20, 25)
MIN_HISTORY = 3
GERMAN_MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def load() -> list[Record]:
    with SAMPLE_CSV.open(encoding="utf-8") as file:
        return [
            Record(dt.date.fromisoformat(row["date"]), row["category"], int(row["amount_cents"]))
            for row in csv.DictReader(file)
            if row["is_duplicate"] != "True"
        ]


def table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def euros(cents: float) -> str:
    return f"{cents / 100:,.0f} €".replace(",", ".")


def percent(value: float) -> str:
    return f"{value * 100:.1f} %"


def main() -> None:
    records = load()
    months = sorted({r.date.strftime("%Y-%m") for r in records})
    complete = months[1:-1]  # the first and the current month are not complete
    categories = sorted({r.category for r in records})
    totals = {m: spent_until(records, m, 31) for m in complete}
    report = [
        "# Forecast – evaluation report",
        "",
        "Generated by `python -m billbuddy.ml.forecast.evaluate` on "
        f"{dt.date.today()} (sample data, {len(complete)} complete months).",
    ]

    # --- Data understanding ---
    values = list(totals.values())
    by_category = {
        c: [spent_until([r for r in records if r.category == c], m, 31) for m in complete] for c in categories
    }
    profile = [mean(spent_until(records, m, d) / totals[m] for m in complete) for d in (1, *CHECK_DAYS)]
    seasonal = {}
    for m in complete:
        seasonal.setdefault(int(m[5:]), []).append(totals[m])
    report += [
        "",
        "## 1. Data understanding",
        "",
        "Monthly totals: "
        f"mean {euros(mean(values))}, median {euros(median(values))}, standard deviation {euros(pstdev(values))}, "
        f"min {euros(min(values))}, max {euros(max(values))}. "
        f"Coefficient of variation {pstdev(values) / mean(values):.2f} – the months differ quite a lot.",
        "",
        table(
            ["Category", "Mean per month", "Share of spending", "Coefficient of variation"],
            [
                [c, euros(mean(v)), percent(sum(v) / sum(values)), f"{pstdev(v) / mean(v):.2f}" if mean(v) else "–"]
                for c, v in sorted(by_category.items(), key=lambda item: -sum(item[1]))
            ],
        ),
        "",
        "Fixed costs (rent, insurance, utilities) hardly vary; travel and shopping vary a lot.",
        "",
        "**Spending is not spread evenly over the month** – average share of the month total spent by:",
        "",
        table(["Day 1", *[f"Day {d}" for d in CHECK_DAYS]], [[percent(p) for p in profile]]),
        "",
        'A third is gone on the 1st (rent). Extrapolating "spent so far / day × days" therefore overshoots badly '
        "at the start of a month.",
        "",
        "Seasonality – mean total per calendar month:",
        "",
        table([GERMAN_MONTHS[m - 1] for m in sorted(seasonal)], [[euros(mean(seasonal[m])) for m in sorted(seasonal)]]),
    ]

    # --- Backtesting ---
    snapshots = []  # one per (month, day, category or total)
    for month in complete:
        history = history_months(records, month)
        if len(history) < MIN_HISTORY:
            continue
        year, number = map(int, month.split("-"))
        for day in CHECK_DAYS:
            today = dt.date(year, number, day)
            known = [r for r in records if r.date <= today]
            result = forecast_month(known, today)
            rows = {None: result.total} | {f.category: f for f in result.categories}
            for kind in [None, *categories]:
                selected = records if kind is None else [r for r in records if r.category == kind]
                hist_totals = [spent_until(selected, h, 31) for h in history]
                rests = [t - spent_until(selected, h, day) for h, t in zip(history, hist_totals, strict=True)]
                spent = spent_until(selected, month, day)
                chosen = rows.get(kind)
                snapshots.append(
                    {
                        "month": month,
                        "day": day,
                        "kind": kind,
                        "actual": spent_until(selected, month, 31),
                        "spent": spent,
                        "mean_rest": mean(rests),
                        "chosen": chosen.forecast_cents if chosen else spent,
                        "low": chosen.low_cents if chosen else spent,
                        "high": chosen.high_cents if chosen else spent,
                        "Extrapolation (spent / day × days)": spent / day * 30.4,
                        "Mean of previous months": mean(hist_totals),
                        "Last month": hist_totals[-1],
                        "Spent + mean rest": spent + mean(rests),
                    }
                )

    # Linear regression, trained only on earlier months (no look into the future)
    for s in snapshots:
        train = [t for t in snapshots if t["month"] < s["month"] and t["day"] == s["day"] and t["kind"] == s["kind"]]
        s["Linear regression"] = None
        if len(train) >= 3:
            model = LinearRegression().fit([[t["spent"], t["mean_rest"]] for t in train], [t["actual"] for t in train])
            s["Linear regression"] = float(model.predict([[s["spent"], s["mean_rest"]]])[0])

    methods = [
        "Extrapolation (spent / day × days)",
        "Mean of previous months",
        "Last month",
        "Linear regression",
        "Spent + mean rest",
        "chosen",
    ]
    names = {"chosen": "Spent + median rest (chosen)"}
    # Compare all methods on the same snapshots (the regression needs 3 earlier months)
    evaluated = [s for s in snapshots if s["Linear regression"] is not None]
    total_rows = [s for s in evaluated if s["kind"] is None]

    def mae(rows, method):
        return mean(abs(s[method] - s["actual"]) for s in rows)

    def mape(rows, method):
        return mean(abs(s[method] - s["actual"]) / s["actual"] for s in rows if s["actual"])

    report += [
        "",
        "## 2. Model comparison (backtesting)",
        "",
        f"{len({s['month'] for s in total_rows})} months × {len(CHECK_DAYS)} days. "
        "MAE = mean absolute error in euros, MAPE = mean absolute error in percent of the real month total.",
        "",
        table(
            ["Method", "MAPE (total)", *[f"MAE day {d}" for d in CHECK_DAYS], "Sum of MAE over categories"],
            [
                [names.get(m, m), percent(mape(total_rows, m))]
                + [euros(mae([s for s in total_rows if s["day"] == d], m)) for d in CHECK_DAYS]
                + [euros(sum(mae([s for s in evaluated if s["kind"] == c], m) for c in categories))]
                for m in methods
            ],
        ),
        "",
        "- Extrapolation is by far the worst at the start of the month (rent on the 1st).",
        "- The mean of previous months ignores what already happened this month.",
        "- The linear regression has too few examples (one per month) and learns noise.",
        '- "Spent + rest" uses both: what is known about this month and the typical rest. '
        "The median is more robust than the mean against single unusual months (holidays, big purchases).",
    ]

    # --- Range ---
    def coverage(rows):
        return mean(s["low"] <= s["actual"] <= s["high"] for s in rows)

    category_rows = [s for s in snapshots if s["kind"] is not None]
    all_totals = [s for s in snapshots if s["kind"] is None]
    report += [
        "",
        "## 3. How reliable is the range?",
        "",
        "The app shows a range of ± one standard deviation of the rest. Share of cases in which the real "
        "month total was inside the range:",
        "",
        f"- Total: {percent(coverage(all_totals))} "
        f"(average width {euros(mean(s['high'] - s['low'] for s in all_totals))})",
        f"- Per category: {percent(coverage(category_rows))}",
        "",
        "So the real result lands inside the range in roughly two out of three cases – which is what "
        "± one standard deviation promises (about 68 % for normally distributed values).",
    ]

    # --- Error over the month ---
    rows = []
    for d in CHECK_DAYS:
        day_rows = [s for s in all_totals if s["day"] == d]
        rows.append([f"Day {d}", percent(mape(day_rows, "chosen")), euros(mae(day_rows, "chosen"))])
    report += [
        "",
        "## 4. Accuracy over the month (chosen method)",
        "",
        table(["Forecast made on", "MAPE", "MAE"], rows),
        "",
        "The later in the month, the more is already known and the smaller the error.",
        "",
    ]

    REPORT_PATH.write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    print(f"\nWritten to {REPORT_PATH}")


if __name__ == "__main__":
    main()
