"""Evaluation of the recurring-cost detection on the sample data (CRISP-DM).
Writes docs/recurring-report.md.

Usage: python -m billbuddy.ml.recurring.evaluate
"""

import csv
import dataclasses
import datetime as dt
from statistics import mean, median, pstdev

from billbuddy.db import PROJECT_ROOT
from billbuddy.ml.categorizer.training_data import SAMPLE_CSV
from billbuddy.ml.recurring import model
from billbuddy.ml.recurring.model import Item, description_key, find_recurring, is_recurring

REPORT_PATH = PROJECT_ROOT / "docs" / "recurring-report.md"


def load() -> list[Item]:
    with SAMPLE_CSV.open(encoding="utf-8") as file:
        return [
            Item(
                None,
                dt.date.fromisoformat(r["date"]),
                r["description"],
                int(r["amount_cents"]),
                r["is_fixed"] == "True",
            )
            for r in csv.DictReader(file)
        ]


def realistic(items: list[Item]) -> list[Item]:
    """Make the fixed costs messier, like real bank data:
    payments due on a weekend arrive on Monday, and prices go up during the period."""
    result = []
    for item in items:
        if item.is_fixed:
            shift = {5: 2, 6: 1}.get(item.date.weekday(), 0)
            amount = item.amount_cents
            if item.date >= dt.date(2026, 1, 1) and description_key(item.description) in {
                "stadtwerke strom",
                "netflix",
            }:
                amount = round(amount * 1.08)
            item = dataclasses.replace(item, date=item.date + dt.timedelta(days=shift), amount_cents=amount)
        result.append(item)
    return result


def series_by_key(items: list[Item]) -> dict[str, list[Item]]:
    groups: dict[str, list[Item]] = {}
    for item in items:
        key = description_key(item.description)
        if key:
            groups.setdefault(key, []).append(item)
    for series in groups.values():
        series.sort(key=lambda i: i.date)
    return groups


def amount_variation(series) -> float:
    """Coefficient of variation of the amounts (standard deviation / mean)."""
    amounts = [i.amount_cents for i in series]
    return pstdev(amounts) / mean(amounts)


def gaps(series):
    return [(b.date - a.date).days for a, b in zip(series, series[1:], strict=False)]


RULES = {
    "Baseline: same description at least 3 times": lambda s: len(s) >= 3,
    "+ gap about one month": lambda s: len(s) >= 3 and 26 <= median(gaps(s)) <= 35,
    "+ regular gaps": lambda s: len(s) >= 3 and 26 <= median(gaps(s)) <= 35 and pstdev(gaps(s)) <= 5,
    "+ similar amount = all rules (chosen)": is_recurring,
}


def scores(groups: dict[str, list[Item]], rule) -> dict:
    tp = fp = fn = 0
    for series in groups.values():
        truth = mean(i.is_fixed for i in series) > 0.5
        predicted = rule(series)
        tp += truth and predicted
        fp += predicted and not truth
        fn += truth and not predicted
    precision = tp / (tp + fp) if tp + fp else 0
    recall = tp / (tp + fn) if tp + fn else 0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0
    return {"tp": tp, "fp": fp, "fn": fn, "precision": precision, "recall": recall, "f1": f1}


def percent(value: float) -> str:
    return f"{value * 100:.1f} %"


def table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def comparison(groups) -> str:
    rows = []
    for name, rule in RULES.items():
        s = scores(groups, rule)
        rows.append([name, s["tp"], s["fp"], s["fn"], percent(s["precision"]), percent(s["recall"]), percent(s["f1"])])
    return table(["Rules", "Found (correct)", "False alarms", "Missed", "Precision", "Recall", "F1"], rows)


def main() -> None:
    items = load()
    groups = series_by_key(items)
    fixed = {k: s for k, s in groups.items() if mean(i.is_fixed for i in s) > 0.5}
    variable = {k: s for k, s in groups.items() if k not in fixed}
    frequent_variable = {k: s for k, s in variable.items() if len(s) >= 3}
    today = max(i.date for i in items)

    report = [
        "# Recurring-cost detection – evaluation report",
        "",
        f"Generated by `python -m billbuddy.ml.recurring.evaluate` on {dt.date.today()} (sample data).",
        "",
        "## 1. Data understanding",
        "",
        f"- {len(items)} expenses → {len(groups)} different descriptions after cleaning "
        f'("Miete Oktober" and "MIETE November" become "miete").',
        f"- {len(fixed)} of them are fixed costs, {len(variable)} are variable; "
        f'{len(frequent_variable)} variable descriptions also appear at least 3 times (e.g. "rewe").',
        "",
        "What separates them (median over the descriptions with at least 3 expenses):",
        "",
        table(
            ["", "Median gap (days)", "Std of the gaps (days)", "Coefficient of variation of the amount"],
            [
                [
                    name,
                    f"{median(median(gaps(s)) for s in g.values()):.0f}",
                    f"{median(pstdev(gaps(s)) for s in g.values()):.1f}",
                    f"{median(amount_variation(s) for s in g.values()):.2f}",
                ]
                for name, g in [("Fixed costs", fixed), ("Variable, frequent", frequent_variable)]
            ],
        ),
        "",
        "Fixed costs come every ~30 days on the same day with the same amount; frequent variable expenses "
        "come at irregular gaps with changing amounts.",
        "",
        "## 2. Which rule does what? (ablation)",
        "",
        "Each line adds one rule. Evaluated per description (series).",
        "",
        comparison(groups),
        "",
        "- Counting alone flags every shop that is visited often.",
        '- The monthly gap removes weekly shopping, the regularity removes shops visited "about monthly".',
        "- The amount rule changes nothing on the sample data (already 100 %). It is kept for real cases the "
        "generator does not produce, e.g. a monthly online order with very different amounts (covered by a unit test).",
        "- 100 % is optimistic: the sample data is tidier than real data. The real test is in daily use.",
        "",
        "## 3. Robustness: messier, more realistic data",
        "",
        "Real bank data is less tidy: payments due on a weekend arrive on Monday, and prices go up "
        "(here: electricity and Netflix +8 % from January 2026).",
        "",
        comparison(series_by_key(realistic(items))),
        "",
        "The tolerances (gap std ≤ 5 days, amount variation ≤ 15 %) absorb these changes.",
        "",
        "## 4. How long until a fixed cost is recognized?",
        "",
    ]

    rows = []
    for months in (2, 3, 4, 6, 12):
        cutoff = today - dt.timedelta(days=round(30.4 * months))
        recent = [i for i in items if i.date > cutoff]
        found = {s.key for s in find_recurring(recent, today)}
        rows.append([f"{months} months", f"{len(found & set(fixed))} of {len(fixed)}", len(found - set(fixed))])
    report += [
        table(["Data available", "Fixed costs recognized", "False alarms"], rows),
        "",
        f"A fixed cost needs {model.MIN_COUNT} payments, i.e. it is recognized in the third month.",
        "",
    ]

    REPORT_PATH.write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    print(f"\nWritten to {REPORT_PATH}")


if __name__ == "__main__":
    main()
